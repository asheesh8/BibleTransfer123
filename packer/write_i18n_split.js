#!/usr/bin/env node
/* Writes app/assets/js/i18n/<code>.js and app/assets/js/i18n-pick.js from
   app/assets/js/i18n.js. Run it (`npm run i18n`) after any change to i18n.js;
   tests/test_i18n_split.js fails while the copies are out of step.

   i18n.js holds every interface language: 1.5 MB, about 380 KB compressed,
   which on 3G is seconds of waiting for text the visitor will never read. Each
   build here is the same machinery with English (the fallback) plus one
   language, and the few lines the language picker and the "change language"
   hint show in every language at once. i18n-pick.js chooses the build while
   the page is still parsing, so it keeps its place among the deferred scripts
   and works off a card (file://) too. */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const JS = path.join(ROOT, 'app', 'assets', 'js');
const SOURCE = path.join(JS, 'i18n.js');
const DATA_START = '  var STRINGS = {';
const DATA_END = '  var shared = ET.libraryScope();';
// Shown for every language at once: the first-run list and the language hint.
const EVERY_LANGUAGE = /^(welcome\.(title|sub|search|suggested|count(\.one)?)|ui\.changelang)$/;

function dictionaries(source) {
  const ET = { libraryScope: () => null, store: { get: (_, d) => d, set() {} }, $$: () => [], $: () => null, esc: v => v };
  const window = { ET };
  vm.runInNewContext(source.replace(DATA_END, '  window.audit = { STRINGS: STRINGS, LANGS: LANGS };\n' + DATA_END),
    { window, document: { documentElement: { setAttribute() {} } }, navigator: { languages: [] } });
  return window.audit;
}

function build(source) {
  const start = source.indexOf(DATA_START);
  const end = source.indexOf(DATA_END);
  if (start < 0 || end < start) throw new Error('i18n.js: cannot find the STRINGS block');
  const { STRINGS, LANGS } = dictionaries(source);
  const codes = LANGS.map(l => l.code);
  const files = {};
  for (const code of codes) {
    const strings = {};
    for (const other of codes) {
      if (other === 'en' || other === code) { strings[other] = Object.assign({}, STRINGS[other]); continue; }
      const few = {};
      for (const [k, v] of Object.entries(STRINGS[other] || {})) if (EVERY_LANGUAGE.test(k)) few[k] = v;
      strings[other] = few;
    }
    const loaded = code === 'en' ? ['en'] : ['en', code];
    files['i18n/' + code + '.js'] =
      '/* Generated by packer/write_i18n_split.js from i18n.js: English and ' + code + ' only. Do not edit. */\n' +
      source.slice(0, start) +
      '  var STRINGS = ' + JSON.stringify(strings) + ';\n' +
      '  var LOADED = ' + JSON.stringify(loaded) + ';\n\n' +
      source.slice(end);
  }
  files['i18n-pick.js'] = PICK.replace('@CODES@', ' ' + codes.join(' ') + ' ');
  return files;
}

const PICK = `/* Generated by packer/write_i18n_split.js. Do not edit.

   Loads the interface text for the one language this page will show, instead
   of all of them. Same choice as i18n.js makes: a language library's fixed
   interface, then a scoped link's ?ui=, then the reader's saved choice. With
   no choice yet (the first-run picker needs every language) or a code not
   built, the complete i18n.js loads. */
(function () {
  var CODES = '@CODES@';
  var code = '', m;
  var lib = window.ET_SHARED_LIBRARY;
  try { code = localStorage.getItem('et.lang') || ''; } catch (e) {}
  if (lib && lib.lang) code = lib.ui || code;
  else if (/[?&]only=[a-z]{3}(?:[&#]|$)/.test(location.search)) {
    m = /[?&]ui=([^&#]*)/.exec(location.search);
    code = m ? decodeURIComponent(m[1]) : 'en';
  }
  var src = CODES.indexOf(' ' + code + ' ') >= 0 ? 'assets/js/i18n/' + code + '.js' : 'assets/js/i18n.js';
  var me = document.currentScript;
  document.write('<script' + (me && me.hasAttribute('data-sync') ? '' : ' defer') + ' src="' + src + '"><\\/script>');
})();
`;

module.exports = { build, SOURCE, JS };

if (require.main === module) {
  const files = build(fs.readFileSync(SOURCE, 'utf8'));
  const dir = path.join(JS, 'i18n');
  fs.mkdirSync(dir, { recursive: true });
  const keep = new Set(Object.keys(files).filter(f => f.startsWith('i18n/')).map(f => path.basename(f)));
  for (const old of fs.readdirSync(dir)) if (!keep.has(old)) fs.unlinkSync(path.join(dir, old));
  for (const [name, body] of Object.entries(files)) fs.writeFileSync(path.join(JS, name), body);
  console.log('Wrote ' + keep.size + ' language builds and i18n-pick.js');
}
