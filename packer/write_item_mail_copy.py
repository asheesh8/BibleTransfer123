#!/usr/bin/env python3
"""Write packer/item_mail_copy.py from the itemshare.mail.* interface strings.

    python3 packer/write_item_mail_copy.py

The email a visitor sends from an item page uses the same words, in the same
language, as the WhatsApp message beside it. Those words live in
app/assets/js/i18n/<code>.js; the server can't load that file, so this copies them
into a small Python module. tests/test_item_mail.py fails if they drift.
"""
import json
import pathlib
import shutil
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "packer" / "item_mail_copy.py"
NODE = shutil.which("node") or "node"
PREFIX = "itemshare.mail."

# Loads every app/assets/js/i18n/<code>.js table and prints the mail lines.
EXTRACT = r"""
const fs = require('fs'), vm = require('vm');
const path = require('path'), dir = process.argv[1];
const window = {};
const context = vm.createContext({ window });
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.js'))) vm.runInContext(fs.readFileSync(path.join(dir, f), 'utf8'), context);
const out = {};
for (const [code, strings] of Object.entries(window.ET_STRINGS)) {
  const mail = {};
  for (const [key, value] of Object.entries(strings)) if (key.startsWith(process.argv[2])) mail[key.slice(process.argv[2].length)] = value;
  if (Object.keys(mail).length) out[code] = mail;
}
process.stdout.write(JSON.stringify(out));
"""


def extract():
    output = subprocess.run([NODE, "-e", EXTRACT, str(ROOT / "app" / "assets" / "js" / "i18n"), PREFIX],
                            check=True, capture_output=True, text=True).stdout
    return {code: dict(sorted(strings.items())) for code, strings in sorted(json.loads(output).items())}


def render(copy):
    lines = ['"""Generated by packer/write_item_mail_copy.py from app/assets/js/i18n/<code>.js. Do not edit."""', "", "COPY = {"]
    for code, strings in copy.items():
        lines.append(f"    {json.dumps(code)}: {{")
        lines += [f"        {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)}," for key, value in strings.items()]
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render(extract()), encoding="utf-8")
    print("Wrote", TARGET)
